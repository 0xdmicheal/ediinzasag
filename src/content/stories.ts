export function byDate(list: Story[] = stories) {
  return [...list].sort((a, b) => b.date.localeCompare(a.date))
}

export function storiesByDesk(desk: Desk) {
  return byDate(stories.filter((story) => story.desk === desk))
}

export function storyBySlug(slug: string) {
  return stories.find((story) => story.slug === slug)
}

export function relatedStories(story: Story, count = 3) {
  return byDate(
    stories.filter(
      (item) => item.slug !== story.slug && (item.desk === story.desk || item.topic === story.topic),
    ),
  ).slice(0, count)
}

export function formatStoryDate(iso: string) {
  const [year, month, day] = iso.split("-")
  return `${year}.${month}.${day}`
}

