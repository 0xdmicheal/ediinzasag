export const topicBySlug = (slug: string) => topics.find((topic) => topic.slug === slug)

// A whole word: \b does not see Cyrillic letters, so the edges are spelled out.
const LETTER = "a-zA-Zа-яА-ЯёЁөӨүҮ"
const wordsPattern = (words: string[]) =>
  new RegExp(`(?<![${LETTER}])(?:${words.map((word) => word.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")).join("|")})(?![${LETTER}])`, "i")
const patterns = new Map(topics.map((topic) => [topic.slug, wordsPattern(topic.words)]))

/** Is this story about the topic: one of its words in the title or dek. */
export function storyOnTopic(topic: TopicHub, story: Pick<Story, "title" | "dek">) {
  return patterns.get(topic.slug)!.test(`${story.title}
${story.dek}`)
}

const priceText = (n: number) => n.toLocaleString("en-US", { minimumFractionDigits: 2, maximumFractionDigits: n >= 100 ? 2 : 3 })

/** "3,597.35₮", "$4,208.40", "1,234.56" for a live quote. */
export function topicValue(topic: TopicHub, live: Pick<LiveQuote, "price">) {
  const price = priceText(live.price)
  if (topic.unit === "₮") return `${price}₮`
  if (topic.unit?.startsWith("$")) return `$${price}`
  return price
}

/** The hand-written close in markets.ts, for a live topic before the quotes job has run. */
export function closeFigure(topic: TopicHub): TopicFigure | undefined {
  if (!topic.quote) return undefined
  const close = topic.quote === "top20" ? top20 : [...commodities, ...fx].find((item) => item.id === topic.quote)
  if (!close) return undefined
  const price = Number(close.price.replace(/,/g, ""))
  const unit = topicUnit(topic)
  return { value: `${topicValue(topic, { price })}${unit ? ` ${unit}` : ""}`, label: `Хаалт · ${close.asOf}`, source: close.source, href: close.href ?? "" }
}

/** "/ унц" after a dollar price, "оноо" after an index. */
export function topicUnit(topic: TopicHub) {
  if (!topic.unit || topic.unit === "₮" || topic.unit === "%") return ""
  return topic.unit.startsWith("$") ? topic.unit.slice(2) : topic.unit
}
