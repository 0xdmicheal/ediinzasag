/*
 * Topic pages (/topic/<slug>): one page per thing Mongolian readers search
 * for every day (долларын ханш, алтны үнэ, инфляц, Оюу толгой…). Each has the
 * number when there is one (live from market_quotes, or the dated figure in
 * markets.ts), a plain explanation, and every story on the topic.
 * scripts/og-pages.mjs prerenders them with the same text for search.
 */

export interface TopicFigure {
  value: string
  label: string
  source: string
  href: string
}

export interface TopicSection {
  heading: string
  text: string
}

export interface TopicHub {
  slug: string
  /** H1 and <title>: the words people type into Google. */
  title: string
  /** Short name for links and chips. */
  short: string
  /** Meta description and the line under the title. */
  dek: string
  /** market_quotes id when the number is live. */
  quote?: string
  /** "₮", "$ / унц", "оноо". */
  unit?: string
  /** A dated figure when the number is not live. */
  figure?: TopicFigure
  sections: TopicSection[]
  /** Words in a story's title or dek that put it on this topic. */
  words: string[]
  /** Markets topics carry the "not investment advice" line. */
  market?: boolean
}

